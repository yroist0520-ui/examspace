/** 长篇阅读选项：由各段落生成（key=段落标记，text=段落首句，超过 60 字符截断） */
function matchOptions(paras: Paragraph[]): Option[] {
  return paras
    .filter((p): p is Paragraph & { marker: string } => Boolean(p.marker))
    .map((p) => {
      const dot = p.text.indexOf('. ');
      const first = dot > 0 ? p.text.slice(0, dot + 1) : p.text;
      const text = first.length > 60 ? `${first.slice(0, 60).replace(/[\s,;:]+$/, '')}…` : first;
      return { key: p.marker, text };
    });
}

